CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(32) PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
 role VARCHAR(20) NOT NULL, salt VARCHAR(32) NOT NULL, password VARCHAR(128) NOT NULL,
 username VARCHAR(30) COLLATE utf8mb4_general_ci UNIQUE,
 email_verified INT NOT NULL DEFAULT 0, active INT NOT NULL DEFAULT 1,
 CHECK(role IN ('coordinator','technician'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS sessions (
 digest VARCHAR(64) PRIMARY KEY, user_id VARCHAR(32) NOT NULL, expires DOUBLE NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS clients (
 id VARCHAR(32) PRIMARY KEY, name VARCHAR(100) NOT NULL, address TEXT NOT NULL,
 latitude DOUBLE NOT NULL, longitude DOUBLE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS visits (
 id VARCHAR(32) PRIMARY KEY, client_id VARCHAR(32) NOT NULL, technician_id VARCHAR(32) NOT NULL,
 scheduled_date VARCHAR(10) NOT NULL, task TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending',
 notes TEXT NOT NULL DEFAULT (''), arrival_at VARCHAR(40), arrival_lat DOUBLE, arrival_lon DOUBLE,
 arrival_accuracy DOUBLE, finished_at VARCHAR(40), version INT NOT NULL DEFAULT 1,
 scheduled_time VARCHAR(5) NOT NULL DEFAULT '', duration_minutes INT NOT NULL DEFAULT 60,
 priority VARCHAR(10) NOT NULL DEFAULT 'normal',
 FOREIGN KEY(client_id) REFERENCES clients(id), FOREIGN KEY(technician_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS routes (
 visit_id VARCHAR(32) PRIMARY KEY, payload LONGTEXT NOT NULL, FOREIGN KEY(visit_id) REFERENCES visits(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id VARCHAR(32) NOT NULL, visit_id VARCHAR(32) NOT NULL,
 action VARCHAR(100) NOT NULL, at VARCHAR(40) NOT NULL, details LONGTEXT NOT NULL DEFAULT ('{}')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS email_codes (
 user_id VARCHAR(32) NOT NULL, purpose VARCHAR(20) NOT NULL, salt VARCHAR(32) NOT NULL,
 digest VARCHAR(128) NOT NULL, expires DOUBLE NOT NULL, attempts INT NOT NULL DEFAULT 0, sent_at DOUBLE NOT NULL,
 PRIMARY KEY(user_id,purpose), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS code_limits (
 user_id VARCHAR(32) PRIMARY KEY, started DOUBLE NOT NULL, count INT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS mail_outbox (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, visit_id VARCHAR(32) NOT NULL UNIQUE, recipient VARCHAR(160) NOT NULL,
 subject VARCHAR(255) NOT NULL, body TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0, next_try DOUBLE NOT NULL DEFAULT 0,
 FOREIGN KEY(visit_id) REFERENCES visits(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS reports (
 visit_id VARCHAR(32) PRIMARY KEY, payload LONGTEXT NOT NULL, actor_id VARCHAR(32) NOT NULL, received_at VARCHAR(40) NOT NULL,
 FOREIGN KEY(visit_id) REFERENCES visits(id), FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS operations (
 user_id VARCHAR(32) NOT NULL, operation_id VARCHAR(64) NOT NULL, digest VARCHAR(64) NOT NULL, response TEXT NOT NULL,
 PRIMARY KEY(user_id,operation_id), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS journeys (
 visit_id VARCHAR(32) PRIMARY KEY, payload LONGTEXT NOT NULL,
 FOREIGN KEY(visit_id) REFERENCES visits(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
